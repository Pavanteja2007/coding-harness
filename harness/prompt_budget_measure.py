"""Phase 3b's deliverable: the before/after prompt-budget table, measured.

Run it
------
    python -m harness.prompt_budget_measure

What it measures
----------------
A real run through the real daily kernel, a scripted deterministic model, the
real 45-tool catalog and the real context builder, at four turn depths
(**1 / 10 / 40 / 80**). Two arms:

* **BEFORE** — every schema sent, every skill body injected. This is the shipped
  default and it is byte-identical to the pre-Phase-3b prompt, which is the
  property that makes the comparison a measurement rather than a story.
* **AFTER** — deferred tool loading plus progressive skill disclosure.

Every number comes from
:class:`harness.prompt_budget.PromptBudgetProfile`, which is P3a's profiler and
reads its sizes from
:class:`harness.agent_kernel.budget.TokenEstimator` — **one estimator**, so the
saving and its cost are measured on the same scale. A net figure computed by
subtracting two differently-estimated numbers is not a net figure.

The cost rows, and why they are the ones that decide this
----------------------------------------------------------
The phase brief is explicit that two rows decide whether the scheme works at
all:

* **tool-search discovery overhead** — every ``tool_search`` call's result bytes.
* **extra round-trips** — a turn on which the model needed a tool it could not
  see. Each costs a full model call.

A scheme that saves 40% of the prompt and adds a round-trip per turn is a NET
LOSS at scale, and only the two cost rows can say which this was. Both are
measured here and neither is smoothed.

The third row the brief asks for, and the one that would make this a regression
----------------------------------------------------------------------------
**Whether the model failed to use tools it could have discovered.** A model that
does not know a tool exists will not search for it, so this is measured by
driving a scripted model through a scripted task that NEEDS a deferred tool and
recording whether it ever called ``tool_search``.

The scripted model cannot *discover* anything, so a naive run would report a
100% failure rate that measures the double rather than the mechanism. This
driver therefore models the question honestly: it drives a model whose replies
are generated by looking up what the task needs in the **deferred set** — i.e.
a model with the capability the corpus says models have — and separately drives
a model that never searches, to show what the same task looks like without it.
Both numbers are reported. The second one is the honest cost of the failure
mode; the first is the mechanism's discoverability.

What this driver does NOT establish
-----------------------------------
No live provider and no Docker lane ran, and nothing here is evidence about how
any real model uses a tool. Every reply is a scripted string. That is stated in
the report's own ``not_established`` field rather than only here.
"""

