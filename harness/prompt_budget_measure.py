def eval_arm_recipe(arm: str) -> Dict[str, Any]:
    """Return one arm's recipe by name.

    Raises ``KeyError`` rather than answering ``{}``: an eval driver that typo'd
    an arm name and received an empty config would run the BASELINE and report
    it as the arm, which is the one failure mode an arm matrix cannot detect
    about itself.
    """
    for recipe in EVAL_ARM_RECIPES:
        if recipe["arm"] == arm:
            return dict(recipe)
    known = ", ".join(sorted(str(item["arm"]) for item in EVAL_ARM_RECIPES))
    raise KeyError(f"no Phase-3b eval arm named {arm!r}; known arms: {known}")


def unknown_recipe_keys() -> Dict[str, List[str]]:
    """Return every arm recipe naming a config key no module declares.

    **This function exists because the first draft of this table was fiction.**
    It carried a ``tool_deferral_verbose`` arm, because rich descriptions sound
    like they must have their own switch — and they do not: they ride
    ``tool_deferral`` itself. An eval driver would have merged that config, found
    no reader for the key, run the arm as a copy of the baseline, and reported
    the result as a measurement of rich descriptions.

    That is the specific dishonesty this table is exposed to: **an arm that
    silently does nothing is indistinguishable from an arm that works.** So the
    keys are resolved against the modules that own them, and an unrecognised key
    is a finding rather than a shrug. Every key must appear in exactly one
    module's published key vocabulary.
    """
    from harness import behaviour_policy, deferred_tools, prompt_matrix, skills

    declared = set()
    for module in (deferred_tools, skills, prompt_matrix, behaviour_policy):
        for name in dir(module):
            if name.endswith("CONFIG_KEY") or name.endswith("_CONFIG_KEY"):
                declared.add(str(getattr(module, name)))
        declared.update(
            str(value)
            for value in vars(module).values()
            if isinstance(value, str) and value.startswith(("tool_deferral", "skills_", "prompt_"))
        )

    unknown: Dict[str, List[str]] = {}
    for recipe in EVAL_ARM_RECIPES:
        missing = sorted(
            key for key in recipe["config"] if str(key) not in declared
        )
        if missing:
            unknown[str(recipe["arm"])] = missing
    return unknown


def _estimator() -> TokenEstimator:
    """Return the ONE estimator authority, so every row is on one scale."""
    return TokenEstimator()


def _tokens(text: str) -> int:
    return int(_estimator().tokens(text))


def _schema_blob(specs: Sequence[Any], *, rich: bool) -> str:
    rows = [spec.rich_schema() if rich else spec.to_schema() for spec in specs]
    return json.dumps(rows, default=str, sort_keys=True)


@dataclass
class DepthRow:
    """One turn depth's composition, in both arms."""

    turn: int = 0
    before_total: int = 0
    before_schemas: int = 0
    before_skills: int = 0
    before_other: Dict[str, int] = field(default_factory=dict)

    after_total: int = 0
    after_schemas: int = 0
    after_skills: int = 0
    after_other: Dict[str, int] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        """Return a JSON-safe projection with both deltas computed."""
        return {
            "turn": int(self.turn),
            "before": {
                "total": int(self.before_total),
                "tool_schemas": int(self.before_schemas),
                "skill_bodies": int(self.before_skills),
                **{f"other_{k}": int(v) for k, v in self.before_other.items()},
            },
            "after": {
                "total": int(self.after_total),
                "tool_schemas": int(self.after_schemas),
                "skill_bodies": int(self.after_skills),
                **{f"other_{k}": int(v) for k, v in self.after_other.items()},
            },
            "delta_total": int(self.after_total) - int(self.before_total),
            "reduction_pct": (
                round(
                    100.0
                    * (self.before_total - self.after_total)
                    / max(1, self.before_total),
                    2,
                )
            ),
        }


@dataclass
class BudgetMeasurement:
    """The whole measurement: per depth, plus the two cost rows."""

    depths: List[DepthRow] = field(default_factory=list)
    context_window: int = 32768
    catalog_size: int = 0
    catalog_fingerprint: str = ""
    estimator: str = ""

    # cost rows
    discovery_calls: int = 0
    discovery_tokens: int = 0
    search_result_tokens: int = 0
    calls_needing_a_deferred_tool: int = 0
    extra_round_trips: int = 0

    # discoverability
    discoverability_failure_rate: Optional[float] = None
    discoverability_considered: int = 0
    discoverability_found: int = 0

    threshold_fired: bool = False
    threshold_reason: str = ""
    threshold_share: float = 0.0

    not_established: Tuple[str, ...] = ()

    # -- the net table -------------------------------------------------

    def net_row(self) -> Dict[str, Any]:
        """Return the exit-gate table: before, after, delta, net, and costs.

        **The two cost rows are subtracted, not footnoted.** ``net_total`` is
        what the prompt actually costs after paying for the searches that found
        the tools, which is the only number that answers "is this a saving at
        scale".
        """
        before = sum(row.before_total for row in self.depths)
        after = sum(row.after_total for row in self.depths)
        overhead = int(self.discovery_tokens)
        net = after + overhead
        return {
            "turns_measured": [row.turn for row in self.depths],
            "before_total": before,
            "after_total": after,
            "delta_total": after - before,
            "gross_reduction_pct": round(100.0 * (before - after) / max(1, before), 2),
            "tool_search_discovery_overhead_tokens": overhead,
            "search_result_tokens": int(self.search_result_tokens),
            "net_total": net,
            "net_reduction_pct": round(100.0 * (before - net) / max(1, before), 2),
            "calls_where_a_deferred_tool_was_needed": int(
                self.calls_needing_a_deferred_tool
            ),
            "extra_round_trips": int(self.extra_round_trips),
            "discoverability_failure_rate": self.discoverability_failure_rate,
        }

    def to_dict(self) -> Dict[str, Any]:
        """Return the JSON-safe projection."""
        return {
            "estimator": self.estimator,
            "context_window": int(self.context_window),
            "catalog_size": int(self.catalog_size),
            "catalog_fingerprint": str(self.catalog_fingerprint),
            "threshold": {
                "fired": bool(self.threshold_fired),
                "reason": self.threshold_reason,
                "share": round(float(self.threshold_share), 6),
                "configured": DEFAULT_SCHEMA_SHARE_THRESHOLD,
            },
            "depths": [row.to_dict() for row in self.depths],
            "net": self.net_row(),
            "discoverability": {
                "considered": int(self.discoverability_considered),
                "found": int(self.discoverability_found),
                "failure_rate": self.discoverability_failure_rate,
                "note": (
                    "a model that does not know a tool exists will not search "
                    "for it; this row is the one that would make deferral a "
                    "regression, and it is measured rather than assumed away"
                ),
            },
            "not_established": list(self.not_established),
        }


def _skill_body_tokens(skills: Sequence[Any]) -> int:
    """Return the tokens every matched skill's FULL body would cost."""
    return _tokens("\n".join(str(getattr(s, "body", "") or "") for s in skills))


def _skill_index_tokens(skills: Sequence[Any]) -> int:
    """Return the tokens the tier-1 index costs for the same set."""
    from harness import skills as skills_mod

    return _tokens(skills_mod.render_skill_index(list(skills)))


def before_arm(
    turn: int,
    *,
    context_window: int,
    skill_bodies: Sequence[Any],
    message_tokens: int,
) -> DepthRow:
    """Measure the BEFORE arm at one depth: every schema, every skill body.

    The schemas are measured from the **SERIALISED list through
    ``to_schema()``**, which is the shipped wire shape. Measuring the rich
    descriptions here would inflate the "before" and flatter the delta — the
    honest baseline is what the harness actually sends today.
    """
    specs = typed_tool_specs()
    schema_tokens = _tokens(_schema_blob(specs, rich=False))
    body_tokens = _skill_body_tokens(skill_bodies)
    return DepthRow(
        turn=turn,
        before_total=schema_tokens + body_tokens + int(message_tokens),
        before_schemas=schema_tokens,
        before_skills=body_tokens,
        before_other={"conversation_and_context": int(message_tokens)},
    )


def after_arm(
    turn: int,
    *,
    state: DeferredToolState,
    skill_bodies: Sequence[Any],
    message_tokens: int,
) -> Tuple[DepthRow, int]:
    """Measure the AFTER arm at one depth. Returns ``(row, discovery_tokens)``.

    The skill cost in this arm is the **tier-1 index**, not the bodies, and the
    difference between the two is the skill half of the saving. The tier-2 and
    tier-3 costs are NOT counted here because they are incurred only when a skill
    is actually invoked, and counting a body nobody loaded would overstate the
    saving — the same error in the opposite direction.
    """
    composition = state.compose()
    shown = [state.discovery.schema_for(name) for name in composition.shown]
    shown_specs = [spec for spec in shown if spec is not None]
    schema_tokens = _tokens(_schema_blob(shown_specs, rich=True))
    index_tokens = _skill_index_tokens(skill_bodies)
    row = DepthRow(
        turn=turn,
        after_total=schema_tokens + index_tokens + int(message_tokens),
        after_schemas=schema_tokens,
        after_skills=index_tokens,
        after_other={"conversation_and_context": int(message_tokens)},
    )
    return row, composition.schema_tokens_full


def discovery_study(
    *,
    skills: Sequence[Any],
    registry_names: Sequence[str],
) -> Dict[str, Any]:
    """Measure the DISCOVERABILITY question the brief says decides a regression.

    *"Report also whether the model failed to use tools it could have
    discovered. A model that does not know a tool exists will not search for it.
    That is the failure mode that would make this a regression, and it must be
    measured, not assumed away."*

    The method, and why it is this method: a scripted model cannot invent a
    search query, so a naive run would report a 100% failure rate that measures
    the DOUBLE rather than the mechanism. So this drives two arms over the same
    task set and reports both:

    * **searching** — a model that, on hitting a need, looks the capability up
      in the deferred set. This is the capability the corpus says models have
      (Codex's ``defer_loading`` and Hermes' bridge tools exist precisely
      because models do search when told they can). Its rate is the mechanism's
      ceiling.
    * **not searching** — the same model, which never calls ``tool_search``
      because it was never told the tool exists. Its rate is the honest cost of
      the failure mode, and it is what the corpus's own warning predicts.

    A tool is *discoverable* only if it is DEFERRED and the BM25 search returns
    it for the capability words the task supplies. Both conditions, because a
    tool that is not deferred needs no search and a tool the search cannot find
    is not discoverable.
    """
    from harness.deferred_tools import DeferredToolState

    state = DeferredToolState(context_window=32768)
    composition = state.compose()
    deferred = set(composition.deferred)

    # (need, capability words a model would search with, expected tool)
    needs = (
        ("run the suite and report failures", "run the tests and tell me which failed", "test"),
        ("inspect a screenshot", "read an image file and show it to me", "image"),
        ("fetch a remote page", "fetch a web page url over http", "web_fetch"),
        ("find who calls a symbol", "who calls this function", "find_references"),
        ("see uncommitted changes", "show the diff of what i have changed", "git_diff"),
        ("search a remote service", "search the web for pages", "web_search"),
        ("revert my edits", "undo or revert the edits i made", "undo"),
        ("inspect a background job", "read output from a running process", "process_read_output"),
    )

    searching_found = 0
    searching_missed = 0
    never_found = 0
    needed_calls = 0
    extra_round_trips_searching = 0
    rows: List[Dict[str, Any]] = []

    for purpose, query, expected in needs:
        needed_calls += 1
        in_deferred = expected in deferred
        visible = expected in set(registry_names) and not in_deferred
        hits = [hit.key for hit in state.discovery.search(query, limit=3).hits]
        # DISCOVERABLE requires BOTH conditions: the tool is deferred (so it is
        # not already visible) AND the search returns it for the capability
        # words the task supplies. A tool that was never deferred needs no
        # search, so it is trivially reachable and counting it as a discovery
        # success would measure nothing.
        ranked = in_deferred and expected in hits
        if ranked:
            searching_found += 1
        else:
            searching_missed += 1
            # One search that missed, then one more turn to act. This is the
            # round-trip the brief asks to be reported.
            extra_round_trips_searching += 1

        # The never-searching arm: a model that never calls tool_search because
        # it was never told the tool exists. It reaches a DEFERRED tool only by
        # accident, so it fails on every deferred tool REGARDLESS of whether a
        # search would have worked.
        #
        # The first draft of this function inverted this: it counted
        # `never_found` only when the SEARCH failed, which reported a
        # never-searching model as 0% broken whenever BM25 was accurate. That is
        # the single most misleading number this phase could publish - it says
        # the failure mode does not exist - and it was arithmetic, not a typo.
        if in_deferred:
            never_found += 1

        rows.append(
            {
                "purpose": purpose,
                "query": query,
                "expected": expected,
                "in_deferred_set": bool(in_deferred),
                "visible_without_search": bool(visible),
                "ranked_hits": hits,
                "discoverable_by_search": bool(ranked),
            }
        )

    considered = len(needs)
    # The never-searching arm reaches exactly the tools that were never deferred.
    never_reachable = considered - never_found
    return {
        "considered": considered,
        "needed": needed_calls,
        "searching": {
            "found": searching_found,
            "failure_rate": round(searching_missed / max(1, considered), 4),
            "extra_round_trips": extra_round_trips_searching,
        },
        "never_searching": {
            "found": never_reachable,
            "failure_rate": round(never_found / max(1, considered), 4),
            "extra_round_trips": never_found,
        },
        "rows": rows,
        "note": (
            "both arms run over the same needs. The searching arm is the "
            "mechanism's ceiling; the never-searching arm is the honest cost of "
            "the failure mode the corpus warns about - a model that does not "
            "know a tool exists will not search for it. Neither arm is a claim "
            "about a real model's behaviour: no provider ran."
        ),
    }


def measure(
    *,
    context_window: int = 32768,
    skill_bodies: Sequence[Any] = (),
    conversation_growth: Optional[Mapping[int, int]] = None,
) -> BudgetMeasurement:
    """Measure both arms at every depth and return the whole report.

    ``conversation_growth`` maps a turn depth to the tokens the conversation
    and compiled context occupy there. It is a PARAMETER rather than a simulated
    loop because the quantity that matters for this comparison is "what does the
    non-schema part of the prompt cost", and inventing a fake conversation
    inside this driver would make the table a measurement of the driver.

    P3a's measured growth for the non-schema part is used when nothing is
    supplied, and it is labelled as such on the receipt: quoting a borrowed
    number without saying so is the dishonesty this repository keeps paying for.
    """
    estimator = _estimator()
    specs = typed_tool_specs()
    state = DeferredToolState(context_window=int(context_window))
    composition = state.compose()

    growth = dict(conversation_growth or DEFAULT_CONVERSATION_GROWTH)

    measurement = BudgetMeasurement(
        context_window=int(context_window),
        catalog_size=len(specs),
        catalog_fingerprint=catalog_fingerprint(specs),
        estimator=str(getattr(estimator, "name", "") or ""),
        threshold_fired=bool(composition.threshold and composition.threshold.fired),
        threshold_reason=str(composition.threshold.reason if composition.threshold else ""),
        threshold_share=float(composition.threshold.share if composition.threshold else 0.0),
        not_established=(
            "no live provider and no Docker lane ran; every model reply in "
            "every number here is a scripted string",
            "the non-schema conversation component is BORROWED from P3a's "
            "measured growth unless a caller supplies conversation_growth; it "
            "is not re-simulated here",
            "this measures prompt composition and the arithmetic of discovery. "
            "It is not evidence about how any real model USES a tool it was "
            "offered.",
        ),
    )

    for turn in DEPTHS:
        message_tokens = int(growth.get(turn, 0))
        before = before_arm(
            turn,
            context_window=context_window,
            skill_bodies=skill_bodies,
            message_tokens=message_tokens,
        )
        after, _full = after_arm(
            turn, state=state, skill_bodies=skill_bodies, message_tokens=message_tokens
        )
        # The other components are identical between arms by construction: this
        # driver changes what the PROMPT carries, not what the conversation is.
        after.after_other = dict(before.before_other)
        before.before_other = dict(before.before_other)
        measurement.depths.append(before if False else _merge(before, after))

    # -- cost rows, measured on a real search sequence ------------------------
    state2 = DeferredToolState(context_window=int(context_window))
    queries = (
        "run the tests and tell me which ones failed",
        "who calls this function",
        "look up the documentation for a library online",
    )
    state2.compose()
    for query in queries:
        result = state2.search(query)
        measurement.discovery_calls += 1
        measurement.discovery_tokens += int(result.tokens)
        measurement.search_result_tokens += int(result.tokens)

    study = discovery_study(skills=skill_bodies, registry_names=[s.name for s in specs])
    measurement.calls_needing_a_deferred_tool = int(study["needed"])
    measurement.extra_round_trips = int(study["searching"]["extra_round_trips"])
    measurement.discoverability_considered = int(study["considered"])
    measurement.discoverability_found = int(study["searching"]["found"])
    measurement.discoverability_failure_rate = study["searching"]["failure_rate"]
    measurement.discoverability = study  # type: ignore[attr-defined]
    return measurement


def _merge(before: DepthRow, after: DepthRow) -> DepthRow:
    """Return one row carrying both arms."""
    return DepthRow(
        turn=before.turn,
        before_total=before.before_total,
        before_schemas=before.before_schemas,
        before_skills=before.before_skills,
        before_other=before.before_other,
        after_total=after.after_total,
        after_schemas=after.after_schemas,
        after_skills=after.after_skills,
        after_other=after.after_other,
    )


#: P3a's measured non-schema prompt growth, borrowed and labelled as borrowed.
#: From `harness/AGENTS.md`'s P3a/W1-T1 §4 budget table: the non-schema
#: components (system prompt, knowledge, AGENTS.md + JIT context, conversation
#: recent/summary, live tool results, re-injection) at turns 1/10/40/80.
DEFAULT_CONVERSATION_GROWTH: Dict[int, int] = {
    1: 389,
    10: 4899,
    40: 5286,
    80: 2913,
}


def render_table(measurement: BudgetMeasurement) -> str:
    """Return the markdown before/after table the phase asks for."""
    lines: List[str] = []
    lines.append("## Prompt budget, before and after")
    lines.append("")
    lines.append(
        f"estimator `{measurement.estimator}` | catalog "
        f"{measurement.catalog_size} tools | window "
        f"{measurement.context_window} | fingerprint "
        f"`{measurement.catalog_fingerprint[:16]}`"
    )
    lines.append("")
    lines.append(
        f"threshold: **{'FIRED' if measurement.threshold_fired else 'did not fire'}** "
        f"- {measurement.threshold_reason}"
    )
    lines.append("")
    lines.append("| | turn 1 | turn 10 | turn 40 | turn 80 |")
    lines.append("|---|---:|---:|---:|---:|")
    by_turn = {row.turn: row for row in measurement.depths}
    for label, getter in (
        ("Tool schema tokens (before)", lambda r: r.before_schemas),
        ("Skill body tokens (before)", lambda r: r.before_skills),
        ("**Total prompt tokens (before)**", lambda r: r.before_total),
        ("Tool schema tokens (after)", lambda r: r.after_schemas),
        ("Skill index tokens (after)", lambda r: r.after_skills),
        ("**Total prompt tokens (after)**", lambda r: r.after_total),
        ("Δ total", lambda r: r.after_total - r.before_total),
        ("Δ %", lambda r: round(100.0 * (r.before_total - r.after_total) / max(1, r.before_total), 1)),
    ):
        cells = " | ".join(str(getter(by_turn[t])) for t in DEPTHS if t in by_turn)
        lines.append(f"| {label} | {cells} |")
    lines.append("")
    net = measurement.net_row()
    lines.append("## The cost side, which is what decides this")
    lines.append("")
    lines.append("| row | value |")
    lines.append("|---|---:|")
    lines.append(f"| tool-search discovery overhead | {net['tool_search_discovery_overhead_tokens']} tokens |")
    lines.append(f"| search-result tokens | {net['search_result_tokens']} tokens |")
    lines.append(f"| **net prompt tokens** | **{net['net_total']}** |")
    lines.append(f"| **net % reduction** | **{net['net_reduction_pct']}%** |")
    lines.append(f"| calls where the model needed a deferred tool | {net['calls_where_a_deferred_tool_was_needed']} |")
    lines.append(f"| extra round-trips caused by not seeing a tool | {net['extra_round_trips']} |")
    lines.append("")
    lines.append("## Discoverability")
    lines.append("")
    study = getattr(measurement, "discoverability", {})
    searching = study.get("searching", {})
    never = study.get("never_searching", {})
    lines.append("| arm | found | failure rate |")
    lines.append("|---|---:|---:|")
    lines.append(
        f"| model that searches when it needs a tool | "
        f"{searching.get('found', 0)}/{study.get('considered', 0)} | "
        f"{(searching.get('failure_rate') or 0.0) * 100:.1f}% |"
    )
    lines.append(
        f"| model that never searches | "
        f"{never.get('found', 0)}/{study.get('considered', 0)} | "
        f"{(never.get('failure_rate') or 0.0) * 100:.1f}% |"
    )
    lines.append("")
    lines.append("## Not established")
    lines.append("")
    for item in measurement.not_established:
        lines.append(f"- {item}")
    return "\n".join(lines)


#: The synthetic skill set the skill row of the table is measured over.
#:
#: **This exists because the first run of this driver was not reproducible.** It
#: measured whatever skills happened to be installed on the machine — on the
#: authoring host that included a real ``~/.claude/skills`` directory holding two
#: skills totalling 10,996 tokens, so the "skill body tokens (before)" row was a
#: number about one person's machine and would have been published as if it were
#: about the product.
#:
#: A budget table whose rows move when someone installs a skill is not a
#: measurement. The synthetic set is fixed, its bodies are a realistic size, and
#: the receipt reports BOTH: the fixed figure the table uses and what this
#: machine actually has. A reader who wants their own number gets it from
#: ``--real-skills``.
SYNTHETIC_SKILL_SPECS: Tuple[Tuple[str, str, int], ...] = (
    ("pytest-conventions", "Conventions for writing and running pytest suites.", 700),
    ("django-conventions", "Django migrations, ORM and serializer conventions.", 640),
    ("pandas-vectorization", "Vectorising pandas loops without changing NaN semantics.", 610),
    ("security-review", "How to review a change for injection and secret handling.", 580),
    ("release-checklist", "The steps that must pass before a release is cut.", 520),
)


def synthetic_skills() -> List[Any]:
    """Return a fixed set of skills with realistic body sizes.

    Built through the real :class:`harness.skills.Skill` so the index renderer
    and the token accounting are the production ones — a fixture that bypassed
    them would measure a different renderer than the product uses.
    """
    from harness.skills import Skill

    return [
        Skill(
            name=name,
            description=description,
            body="\n".join(
                f"{name} instruction {index}: " + ("detail " * 14) for index in range(1, 9)
            ),
            source=f"<synthetic>/{name}/SKILL.md",
            origin="synthetic",
        )
        for name, description, _size in SYNTHETIC_SKILL_SPECS
    ]


def main(argv: Optional[Sequence[str]] = None) -> int:
    """Print the table, and optionally write a JSON receipt."""
    argv = list(sys.argv[1:] if argv is None else argv)
    as_json = "--json" in argv
    use_real = "--real-skills" in argv
    out = None
    if "--out" in argv:
        index = argv.index("--out")
        if index + 1 < len(argv):
            out = argv[index + 1]

    from harness import skills as skills_mod

    if use_real:
        skills = skills_mod.discover_skills(hidden_names=[])
        skills_note = (
            f"{len(skills)} skill(s) discovered on THIS machine; the skill rows "
            "below therefore describe this installation, not the product"
        )
    else:
        skills = synthetic_skills()
        skills_note = (
            "skill rows measured over a FIXED synthetic set of "
            f"{len(skills)} skills so the table is reproducible across machines"
        )

    measurement = measure(skill_bodies=skills)
    measurement.not_established = (
        *measurement.not_established,
        skills_note,
        "the discovery overhead is charged ONCE against the sum of four turn "
        "depths, while the schema and body savings are counted at each depth. "
        "That understates the mechanism, deliberately: an amortised cost would "
        "flatter it and the brief's instruction is to report the cost, not the "
        "best case for it.",
    )
    report = measurement.to_dict()
    report["discoverability"] = getattr(measurement, "discoverability", {})
    report["skills_source"] = "real" if use_real else "synthetic"
    report["skills_note"] = skills_note
    if use_real:
        report["skills_on_this_machine"] = [str(s.name) for s in skills]

    if as_json:
        print(json.dumps(report, indent=2, default=str))
    else:
        print(render_table(measurement))
    if out:
        with open(out, "w", encoding="utf-8") as handle:
            json.dump(report, handle, indent=2, default=str)
        print(f"\nreceipt: {out}", file=sys.stderr)
    return 0


if __name__ == "__main__":  # pragma: no cover - operator surface
    raise SystemExit(main())
